func blockedDNS(name string, blockAds, blockTrackers bool) bool {
	for name != "" {
		if (blockAds && ads[name]) || (blockTrackers && trackers[name]) {
			return true
		}
		_, suffix, ok := strings.Cut(name, ".")
		if !ok {
			break
		}
		name = suffix
	}
	return false
}

// DNS questions generated by the Android resolver use an uncompressed QNAME.
func dnsQuestion(packet []byte) (string, int) {
	if len(packet) < 17 || packet[2]&0xf8 != 0 || binary.BigEndian.Uint16(packet[4:6]) != 1 {
		return "", 0
	}
	labels := make([]string, 0, 5)
	for off := 12; off < len(packet) && off <= 267; {
		n := int(packet[off])
		off++
		if n == 0 {
			if off+4 > len(packet) {
				break
			}
			return strings.ToLower(strings.Join(labels, ".")), off + 4
		}
		if n > 63 || off+n > len(packet) || off+n > 267 {
			break
		}
		label := string(packet[off : off+n])
		if strings.Contains(label, ".") {
			break
		}
		labels = append(labels, label)
		off += n
	}
	return "", 0
}

func negativeDNS(question []byte, code byte) []byte {
	answer := append([]byte(nil), question...)
	answer[2] |= 0x80
	answer[3] = 0x80 | code
	clear(answer[6:12])
	if len(answer) == 12 {
		clear(answer[4:6])
	}
	return answer
}
